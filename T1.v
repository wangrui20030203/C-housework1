`timescale 1ns/1ps
// ============================================================================
// 模块名 : T1 —— 调度器 / 节拍器
// ============================================================================
// 一句话功能:
//   像素芯片的"时序大脑"。负责三件事:
//   ① 分频: 外部 200MHz ÷10 = 20MHz(50% 占空比), 作为状态机节拍;
//   ② 曝光计时: 每帧开头在 S0 累计曝光 ΔT(EXPOSURE_TICKS 个 20M 周期);
//   ③ 状态调度: S0(曝光)->S1(等 pixel_ack=1)->S2(等 pixel_ack=0)->S3(逐列输出)
//      普通行输出完回 S1 直接下一行; 第 255 行输出完回 S0 重新曝光(新一帧)。
//
// 端口说明:
//   输入:
//     clk_200M_ext : 外部 200MHz 时钟源
//     rst          : 复位, 高电平有效(高=复位, 低=释放; 与 PDF 波形一致)
//     enable       : 启动信号(0: 停 S0 空闲; 1: 正常运行)
//     pixel_ack    : 像素阵列应答(数据就绪), 仅 S1 期间为高
//   输出:
//     state   : 当前状态 S0(00)/S1(01)/S2(10)/S3(11), 2bit
//     clk_200M: 200MHz 全覆盖直通输出(一直跳, 观察用)
//     clk_20M : 内部分频出的 20MHz(观察用)
//
// 状态机流程(20M 域):
//   S0(00) 曝光: 数满 EXPOSURE_TICKS 拍 -> 同拍进 S1(曝光期间 state 保持 00)
//   S1(01) 行应答: 等 pixel_ack=1(数据就绪) 才进 S2, 否则停在 S1 等
//   S2(10) 缓冲写入: 等 pixel_ack=0(交接完成) 才进 S3, 否则停在 S2 等
//   S3(11) 逐列输出: 固定 S3_TICKS=33 拍(30 个 20M 周期余量核算见下)
//          -> 普通行回 S1(跳过 S0 提速); 第 255 行回 S0 并置曝光
//
//   T2 在 200M 域数列 320 列 + 行完成 1 拍 = 321 拍 = 32.1 个 20M 周期;
//   安全版 T2 对 state 打两拍同步(晚 2 个 200M), 实际占用 2+321=323 个 200M
//   < 33 拍(330 个 200M), 余量 7 拍, 保证 T2 能在 S3 结束前完整输出一行。
//
// 参数:
//   EXPOSURE_TICKS: 曝光时间 ΔT, 单位=clk_20M 周期(20MHz 下 1 周期=50ns)
//                   默认 100 周期 = 5us; 例化时可覆盖(测试用 10 周期)
// ============================================================================
module T1 #(
    parameter [19:0] EXPOSURE_TICKS = 20'd100   // 曝光时间(clk_20M 周期数)
)(
    // ---------------- 输入 ----------------
    input        clk_200M_ext,   //  外部 200MHz 时钟源
    input        rst,            // 复位(高有效: 高=复位, 低=释放; 与PDF波形一致)
    input        enable,         // 启动
    input        pixel_ack,      // 像素阵列应答(数据就绪判断)

    // ---------------- 输出 ----------------
    output [1:0] state,          // 四状态
    output       clk_200M,       // 200M 全覆盖输出(一直跳)
    output       clk_20M         // 内部分频 20MHz
);

// ----------------------------------------------------------------------------
// ① 分频器: 200M ÷10 -> 20M (50% 占空比)
//    原理: div_cnt 计 0~4 共 5 拍翻转一次 clk_20M_r,
//          一个 20M 周期 = 10 个 200M 周期(高 5 拍 + 低 5 拍)
// ----------------------------------------------------------------------------
reg [2:0] div_cnt;     // 分频计数器 0~4
reg clk_20M_r;         // 20MHz 寄存器
always @(posedge clk_200M_ext or posedge rst) begin
    if (rst) begin
        div_cnt   <= 3'd0;
        clk_20M_r <= 1'b0;
    end
    else if (div_cnt == 3'd4) begin
        div_cnt   <= 3'd0;
        clk_20M_r <= ~clk_20M_r;   // 每 5 拍翻转一次 -> 20MHz
    end
    else div_cnt <= div_cnt + 1'b1;
end
assign clk_20M = clk_20M_r;

// ----------------------------------------------------------------------------
// ② 状态机: S0 曝光 -> S1(等 ack) -> S2(等 ack 撤) -> S3(固定节拍)
// ----------------------------------------------------------------------------
localparam [1:0] S0 = 2'b00, S1 = 2'b01, S2 = 2'b10, S3 = 2'b11;
localparam [5:0] S3_TICKS = 6'd33;   // S3 固定 33 个 clk_20M(硬约束, 不许改小)
localparam [7:0] LAST_ROW = 8'd255;  // 最后一行索引

reg [1:0]  state_r;     // 状态寄存器
reg [19:0] exp_cnt;     // 曝光计数(clk_20M 周期)
reg [7:0]  row_cnt;     // 行计数(0~255)
reg [5:0]  s3_cnt;      // S3 内节拍计数(0~32)
reg        exp_phase;   // 1=曝光阶段(内部信号)
assign state = state_r;

always @(posedge clk_20M or posedge rst) begin
    if (rst) begin
        // 复位: 回 S0, 清所有计数, 标记需要曝光
        state_r   <= S0;
        exp_cnt   <= 20'd0;
        row_cnt   <= 8'd0;
        s3_cnt    <= 6'd0;
        exp_phase <= 1'b1;
    end
    else if (!enable) begin
        // 未启动: 停在 S0(曝光/空闲), 清计数
        state_r   <= S0;
        exp_cnt   <= 20'd0;
        row_cnt   <= 8'd0;
        s3_cnt    <= 6'd0;
        exp_phase <= 1'b1;
    end
    else begin
        case (state_r)
            // --------------------------------------------------------------
            // S0(00): 曝光计时。数满 EXPOSURE_TICKS 拍 -> 同拍进 S1。
            //         曝光是"内部阶段", 期间 state 保持 00。
            // --------------------------------------------------------------
            S0: begin
                if (exp_phase) begin
                    // 曝光中: 累计到 EXPOSURE_TICKS 拍即曝光结束
                    if (exp_cnt + 1'b1 == EXPOSURE_TICKS) begin
                        exp_cnt   <= 20'd0;
                        exp_phase <= 1'b0;   // 曝光结束, 进入读出
                        state_r   <= S1;
                    end
                    else exp_cnt <= exp_cnt + 1'b1;
                end
                else state_r <= S1;   // 非曝光(帧间跳转时)直接进 S1
            end
            // --------------------------------------------------------------
            // S1(01): 行应答 —— 数据就绪判断(pixel_ack 握手)
            //   等像素阵列 ack=1(该行数据已准备好) 才进 S2 写缓冲
            // --------------------------------------------------------------
            S1: begin
                if (pixel_ack)      state_r <= S2;
                else                state_r <= S1;   // 没就绪就继续等
            end
            // --------------------------------------------------------------
            // S2(10): 缓冲写入 —— 等 ack 释放(交接完成)才进 S3
            //   像素阵列交出数据后 ack 拉低, 表示 T2 可以开始逐列读出
            // --------------------------------------------------------------
            S2: begin
                if (!pixel_ack)     state_r <= S3;
                else                state_r <= S2;   // ack 还没撤就继续等
            end
            // --------------------------------------------------------------
            // S3(11): 逐列输出 —— 固定 S3_TICKS 拍
            //   普通行输出完回 S1(跳过 S0, 提速); 第 255 行输出完回 S0 重曝光
            // --------------------------------------------------------------
            S3: begin
                if (s3_cnt == S3_TICKS - 1'b1) begin
                    s3_cnt <= 6'd0;
                    if (row_cnt == LAST_ROW) begin
                        row_cnt   <= 8'd0;
                        exp_phase <= 1'b1;   // ★ 一帧结束 -> 重新曝光
                        state_r   <= S0;
                    end
                    else begin
                        row_cnt <= row_cnt + 1'b1;
                        state_r <= S1;       // 普通行回 S1, 不经过 S0
                    end
                end
                else s3_cnt <= s3_cnt + 1'b1;
            end
            default: state_r <= S0;
        endcase
    end
end

// ----------------------------------------------------------------------------
// ③ 200M 时钟输出 —— 全覆盖直通(一直跳, 无门控, 减少干扰)
// ----------------------------------------------------------------------------
assign clk_200M = clk_200M_ext;
endmodule
